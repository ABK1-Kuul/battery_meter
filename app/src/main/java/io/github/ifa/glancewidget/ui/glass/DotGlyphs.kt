    fun getGlyph(char: Char): List<String> {
        return GLYPH_MAP[char] ?: BLANK_GLYPH
    }

    fun isLit(char: Char, row: Int, col: Int): Boolean {
        if (row !in 0 until ROW_COUNT || col !in 0 until COL_COUNT) return false
        val glyph = getGlyph(char)
        return glyph[row][col] == '1'
